// #1702 — the write half of the `initialize` control-request capture: the writer
// that puts #1701's record on disk under a minted name, into a directory its
// caller chooses, and the offline round trip proving no field is dropped on the
// way. The name came from #1696's one-input namer until #1722 migrated the writer
// onto #1712's arm-carrying one.
//
// A measurement whose only trace is a test log evaporates when the run ends, so
// #1688's artifact is the point — and an artifact is worth committing only if it
// is COMPLETE (no field silently dropped on the way to disk), BOUNDED (no
// unbounded credential-bearing capture) and ATOMIC (no half-written residue
// stranded for a later commit). None of the three needs a claude binary. This
// file settles all three.
//
// # What this file deliberately is not
//
// It adds no field to initControlFixtureRecord and mints no second fixture —
// both are #1701's, and this file reads them.
//
// The scope limit that remains is the ROUND TRIP's, not the file's:
// initControlFullRecord's stderr_capture is well under stderrFixtureCap, so
// writeInitControlFixture's capFixtureCapture call is a no-op inside
// TestInitControlFixture_RoundTripsEveryFieldIntoOneNamedEntry and that row
// compares equal on both sides. TestInitControlFixture_WriterCapsStderrCapture
// mutates the record to an over-cap capture and is what proves BOUNDED. The
// writer's no-mutation contract is structurally the same claim — observing it
// needs a capture the cap actually shortens — so it rides there too, exactly as
// TestPoolRevokeFixture_WriterCapsChildOutputCapture carries the sibling's rather
// than its round trip. No live run: that is #1688.
//
// #1722 added a third test here for the same structural reason the cap has its
// own: TestInitControlFixture_RoundTripsAnUnansweredWaitBesideCapturedBytes needs
// a record the fully-populated fixture cannot be — captured response bytes beside
// an UNSATISFIED wait — and #1701's non-zero property forbids that pair there,
// since a bool is non-zero only when true. It lands in this file rather than the
// record's because it writes and reads back, and this is the file whose
// finOfflineExecBans entry permits os.WriteFile and os.ReadFile.
//
// # What the round trip catches, and what it cannot
//
// The read-back decodes through the struct that wrote the file, so it is
// symmetric and CANNOT catch a misspelled JSON tag. #1662's code review sharpened
// that limit: even a UNIQUE wrong tag round-trips green, because only a COLLIDING
// tag makes encoding/json drop both. Applying initControlFixtureFields to both
// sides does not change it — the listing labels failure messages here rather than
// checking anything.
//
// The limit is stated, not claimed away, and it must NOT be dismissed the way
// #1662's header dismisses its own. #1662's key names are read by humans alone.
// THESE ARE NOT: #1690's decoder and #1692's fake read this contract, so a
// misspelled tag here is a real defect two tickets downstream — one this test is
// simply not the instrument for. The instrument is a reviewer diffing #1701's
// hand-written initControlFixtureFields against the struct's tags, which is why
// that listing must never be regenerated by reflection.
//
// What the round trip does catch is a field dropped or tagged `json:"-"`, a
// COLLIDING pair of tags, a writer that formats its own filename instead of
// minting one, a writer that ignores its dir parameter, and a rename that never
// happened.
//
// # Offline, and the one ban this file must not copy from its siblings
//
// This file reaches no live claude, no daemon, no subprocess and no credential:
// it must not reach resolveClaudeBin, probeClaudeVersion, WithWorktree,
// WithWorktreeAuthenticated or captureClaudeVersion, nor os.Getenv, os.Environ or
// os.LookupEnv, nor packageDir or any of the wrappers setModeFixturePath,
// writeSetModeFixture and writeFixture that resolve the committed testdata/
// through it.
//
// It DOES write, read back and list a directory — that is its entire subject — so
// unlike initialize_control_names_test.go and initialize_control_record_test.go
// it bans none of the os read/write helpers. The relative-path hazard those bans
// close for the two files that perform no I/O — `go test` runs in the package
// source directory, so a RELATIVE os.WriteFile("testdata/…") reaches the
// committed fixtures without naming packageDir at all — is closed here instead by
// the exactly-one-entry assertion below: bytes that escaped to a relative
// testdata/ leave the t.TempDir() holding ZERO entries.
//
// TestFinOfflineFilesReachNoExecHelper enforces the ban over this file's AST
// rather than over this paragraph — it parses without parser.ParseComments
// precisely so the check cannot answer itself out of the sentence that states it.
//
//	go test -tags e2e_realclaude -race -count=1 -v \
//	  -run 'TestInitControlFixture_|TestFinOfflineFilesReachNoExecHelper' \
//	  ./internal/e2e/realclaude/
//
// Both must report PASS — not SKIP, not "no tests to run" — on a machine with no
// claude and no credentials. Read the count of tests that executed, never the
// exit code: this package is behind the e2e_realclaude tag, `make check` never
// compiles it, and the suite exits 0 both on a build failure and on a full
// credentials skip.

