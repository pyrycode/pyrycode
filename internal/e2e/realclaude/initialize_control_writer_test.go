// --- the writer -----------------------------------------------------------------

// writeInitControlFixture writes rec into dir and returns the written path.
//
// dir is a PARAMETER, deliberately — unlike writeSetModeFixture, which hardcodes
// packageDir(t)/testdata and is correct for #1595's live run. That is what lets
// this writer settle here against a t.TempDir(), with #1688 passing the real
// testdata/ later. os.MkdirAll is a no-op against a t.TempDir() and is kept for
// the same reason the sibling writer keeps it: #1688's directory may not exist.
//
// The filename is MINTED by initControlArmFixtureName from ClaudeVersion and Arm,
// BOTH passed through UNMODIFIED, never formatted here and never slugged here —
// that namer owns both columns. A writer that interpolates its own
// "initialize_control_v%s_%s.json" puts #1688's committed artifact back inside the
// overwrite hazard #1696's lock exists to close, with #1696's own test still
// green; one that interpolates the ARM raw reopens the traversal hazard
// setModeFixtureName still carries, which is the wrong pattern sitting in this
// same package waiting to be copied.
//
// #1722 migrated this off the one-input initControlFixtureName. Through that namer
// all three of #1715's arms mint one path: the last arm wins and the other two
// vanish with nothing red anywhere. The input is claude_version and not
// claude_version_raw: #1701's distinctness property keeps the two strings apart,
// and the raw form carries a space and parens that slug to something else
// entirely.
//
// DO NOT ADD A MEMBERSHIP OR SHAPE GUARD ON Arm HERE. Rejecting an arm outside
// initControlArms rejects initControlFullRecord's own synthetic arm — which is
// deliberately not a declared one, so that #1701's slug subtest has something to
// pin — and fatals the round trip below. The containment guarantee is lexical and
// belongs to the namer.
//
// rec is never mutated — the cap lands on a local copy. THE SHALLOW COPY IS
// SUFFICIENT ONLY BECAUSE THE SOLE MUTATION IS TO A string FIELD: `out := *rec`
// shares every slice header with the caller's record, so a future writer that
// capped one of the slice-valued fields would be writing through the caller's
// backing array from behind a copy that looks defensive. Nothing here proves the
// cap bound or the no-mutation contract; both are
// TestInitControlFixture_WriterCapsStderrCapture's.
//
// Failure is always t.Fatalf naming claude_version and arm and the error and
// NOTHING ELSE: a %+v of the record would move up to stderrFixtureCap bytes of
// child output out of the bounded file and into an unbounded run log, the exact
// thing the cap exists to prevent. Both are safe to print for the same reason —
// each is already in the filename and neither came from the child. The arm joined
// the message with #1722's per-arm path: once #1715 writes three fixtures, a
// failure that cannot say which arm failed is a real diagnosis gap.
func writeInitControlFixture(t *testing.T, dir string, rec *initControlFixtureRecord) string {
	t.Helper()

	out := *rec
	out.StderrCapture = capFixtureCapture(out.StderrCapture)

	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatalf("#1702: mkdir fixture dir for claude_version %q arm %q: %v",
			out.ClaudeVersion, out.Arm, err)
	}
	path := filepath.Join(dir, initControlArmFixtureName(out.ClaudeVersion, out.Arm))
	data, err := json.MarshalIndent(&out, "", "  ")
	if err != nil {
		t.Fatalf("#1702: marshal fixture for claude_version %q arm %q: %v",
			out.ClaudeVersion, out.Arm, err)
	}
	// Temp file and rename, the discipline both sibling writers use: an
	// interrupted run must not strand a half-written fixture under the target
	// name for a later commit.
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		t.Fatalf("#1702: write fixture tmp for claude_version %q arm %q: %v",
			out.ClaudeVersion, out.Arm, err)
	}
	if err := os.Rename(tmp, path); err != nil {
		t.Fatalf("#1702: rename fixture for claude_version %q arm %q: %v",
			out.ClaudeVersion, out.Arm, err)
	}
	return path
}

// --- the raw-JSON normaliser --------------------------------------------------

// compactInitControlRawRows returns rows with every raw-JSON-bearing row
// normalised through compactRawMessages, plus the names of the rows it touched.
//
// json.MarshalIndent indents INSIDE an embedded raw message, so an envelope
// written and read back is not byte-equal and a PERFECTLY CORRECT writer reddens.
// #1662 hit this with one such field; this record has THREE, of two different Go
// types — control_request_sent is a json.RawMessage, control_responses and
// stdout_events are []json.RawMessage. Measured on this toolchain 2026-08-22,
// byte-equality after the round trip is false for all three shapes and compaction
// restores it for all three; a plain string field is unaffected. Normalising only
// control_responses — #1662's shape — is red on arrival here, not a latent risk.
//
// SELECTION IS BY THE ROW'S GO TYPE, NOT BY THE THREE NAMES. #1701's length
// assertion guarantees a fourth raw-JSON field added later arrives with a listing
// row, and a name-scoped normaliser would then redden against an honest writer.
// The type switch covers it automatically. The three names are still the
// checkable list, which is what the touched-name return is for: the round trip
// asserts the touched set is exactly those three, so a normaliser widened to
// blind rows it should not is caught, and one that silently stopped matching
// reports as one clear failure instead of three confusing row mismatches.
//
// compactRawMessages takes []json.RawMessage, so the single-valued field is
// wrapped and unwrapped HERE rather than growing a second helper. Unwrapping
// keeps the row's dynamic type identical to the record's, so a failure message
// reads as that field's own shape.
//
// ONE DIAGNOSIS TRAP, expected rather than broken. A dropped or `json:"-"`-tagged
// control_request_sent leaves the read-back side nil, and json.Compact over nil
// returns "unexpected end of JSON input" — so that mutant surfaces as
// compactRawMessages' own t.Fatalf, which carries #1662's ticket number and names
// control_responses explicitly. The verdict is correct and the mutant IS red; the
// diagnosis points at the wrong file and the wrong field. The two slice-valued
// fields degrade cleanly to an empty slice and report as ordinary row mismatches.
func compactInitControlRawRows(t *testing.T, rows []initControlFixtureField) ([]initControlFixtureField, []string) {
	t.Helper()

	out := make([]initControlFixtureField, 0, len(rows))
	touched := make([]string, 0, len(rows))
	for _, row := range rows {
		switch v := row.value.(type) {
		case json.RawMessage:
			row.value = compactRawMessages(t, []json.RawMessage{v})[0]
			touched = append(touched, row.name)
		case []json.RawMessage:
			row.value = compactRawMessages(t, v)
			touched = append(touched, row.name)
		}
		out = append(out, row)
	}
	return out, touched
}

// --- the round trip -------------------------------------------------------------

// TestInitControlFixture_RoundTripsEveryFieldIntoOneNamedEntry is #1702's AC 2 and
// AC 3: every field of #1701's fully-populated record survives
// write-then-read-back, and the target directory afterwards holds exactly one
// entry, named exactly what initControlArmFixtureName mints from the record's own
// claude_version and arm.
//
// The subtests share one written artifact and are deliberately NOT parallel; the
// parent owns the tempdir.
//
// It does not restate #1701's properties. Non-zero and same-typed distinctness
// ship in TestInitControlFullRecord_PinsEveryFieldAndTheSluggableVersionToken and
// are preconditions this test consumes rather than assertions it repeats — and
// there is no cap row, because the fixture's capture is far under the cap and
// that row is TestInitControlFixture_WriterCapsStderrCapture's whole subject.
func TestInitControlFixture_RoundTripsEveryFieldIntoOneNamedEntry(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	rec := initControlFullRecord()
	path := writeInitControlFixture(t, dir, rec)

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("#1702: read back the fixture for claude_version %q: %v", rec.ClaudeVersion, err)
	}
	var got initControlFixtureRecord
	if err := json.Unmarshal(data, &got); err != nil {
		t.Fatalf("#1702: decode the fixture for claude_version %q: %v", rec.ClaudeVersion, err)
	}

	// Both sides go through the SAME listing, applied to the written record and
	// to its decode. There is deliberately no length guard before the zip: both
	// slices come from one function over one struct type, so a divergence is
	// impossible and the guard could never redden.
	want, touched := compactInitControlRawRows(t, initControlFixtureFields(rec))
	have, _ := compactInitControlRawRows(t, initControlFixtureFields(&got))

	t.Run("every field survives the round trip", func(t *testing.T) {
		for i := range want {
			if !reflect.DeepEqual(want[i].value, have[i].value) {
				// Printing both values is safe HERE AND ONLY HERE: every value in
				// this record is a #1701 synthetic literal, and the diagnostic is
				// worth far more than protecting a 53-byte fixture string. #1688
				// fills this same record from a live child and must not inherit
				// the pattern — its stderr_capture is real, bounded child output,
				// and TestInitControlFixture_WriterCapsStderrCapture's rows report
				// lengths and a short prefix for exactly that reason.
				t.Errorf("#1702: %s did not survive the round trip: wrote %v, read back %v; "+
					"#1688 commits this record as its only durable trace",
					want[i].name, want[i].value, have[i].value)
			}
		}
	})

	t.Run("the normaliser touches exactly the three raw-JSON rows", func(t *testing.T) {
		// The type-scoped selection above is what keeps a fourth raw-JSON field
		// covered automatically; this is what keeps that scoping honest. Sorted
		// because the claim is about the SET of rows, not the listing's order.
		wantTouched := []string{"control_request_sent", "control_responses", "stdout_events"}
		gotTouched := append([]string(nil), touched...)
		sort.Strings(gotTouched)

		if !reflect.DeepEqual(gotTouched, wantTouched) {
			t.Errorf("#1702: the normaliser touched %v, want exactly %v: widened, it blinds more "+
				"than the whitespace json.MarshalIndent introduces and a genuinely altered row "+
				"reads back equal; narrowed, it reddens against an honest writer because an "+
				"embedded raw message is never byte-equal after a round trip",
				gotTouched, wantTouched)
		}
	})

	// One assertion, four hazards: a .tmp stranded beside the target by a copy
	// instead of a rename, any stray file, a write that escaped to the package's
	// real testdata/ (which leaves this tempdir at ZERO entries — the
	// relative-path hazard no AST ban can close), and a writer that minted its
	// target name some other way instead of calling initControlArmFixtureName —
	// which since #1722 covers a writer left on the one-input initControlFixtureName,
	// one interpolating its own "initialize_control_v%s_%s.json", and one passing a
	// hardcoded arm instead of the record's.
	//
	// The last is non-vacuous only because BOTH columns of #1701's fixture carry a
	// literal versionSlug rewrites: claude_version's uppercase run and arm's. Against
	// a slug-clean token it is 0-red on the version column; against a clean declared
	// arm it is 0-red on the arm column, which is the whole reason that literal is
	// "after_completed_turn-FIXTURE" and not a declared arm.
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("#1702: list the fixture directory for claude_version %q: %v", rec.ClaudeVersion, err)
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	wantName := initControlArmFixtureName(rec.ClaudeVersion, rec.Arm)
	if len(names) != 1 || names[0] != wantName {
		t.Errorf("#1702: the target directory holds %q, want exactly [%q]: a .tmp left here is a "+
			"half-written fixture a later commit would pick up, an empty directory means the "+
			"bytes went somewhere the caller never chose, and a differently-spelled entry means "+
			"the writer formats its own name, or hardcodes an arm, instead of minting through "+
			"initControlArmFixtureName from the record's own claude_version and arm",
			names, wantName)
	}
}

// --- the unanswered wait ------------------------------------------------------------

// TestInitControlFixture_RoundTripsAnUnansweredWaitBesideCapturedBytes is #1722's
// second half: a record carrying captured response bytes AND
// control_response_within_wait FALSE is representable, and it survives a write and
// a read-back carrying both halves.
//
// THAT PAIR IS THE WHOLE POINT, and it is reachable on the live path rather than
// hypothetical. runInitControlChild's setModeWaitFor returns when its budget
// expires, and ControlResponses is snapshotted much later — after stdinPipe.Close()
// and cmd.Wait(). A response landing in that window is captured with the wait
// already false. "There are response bytes" and "the wait was satisfied" are two
// different facts, and before #1722 only the first survived the run.
//
// It is the SOLE red for a control_response_within_wait derived from
// len(ControlResponses) > 0 instead of from the wait's own result. The main round
// trip cannot catch that mutant: initControlFullRecord carries the COHERENT pair —
// bytes and a satisfied wait — because a bool is non-zero only when true, so
// #1701's non-zero property forbids the discriminating case there. Hence a second
// record instance here rather than a change to the fixture.
//
// The failure messages report the two field names and a response COUNT, never the
// response bytes. runInitControlChild fills this same record from a live child, and
// this file's sibling rows deliberately report lengths and short prefixes for that
// reason; this must not be the site that breaks the pattern.
func TestInitControlFixture_RoundTripsAnUnansweredWaitBesideCapturedBytes(t *testing.T) {
	t.Parallel()

	// A fresh pointer, mutated here and shared with nothing: initControlFullRecord
	// is a function and not a package-level var precisely so this and the cap test's
	// parallel subtests cannot race on one record.
	rec := initControlFullRecord()
	rec.ControlResponseWithinWait = false

	// The vacuity control, and it must Fatalf rather than skip — precheck's
	// precedent in the cap test below. If a later edit empties the fixture's
	// responses, this row stops discriminating between "the field is measured" and
	// "the field is always false" while still passing, and a row that cannot
	// discriminate is a broken instrument.
	if len(rec.ControlResponses) == 0 {
		t.Fatalf("#1722: the fixture carries no control_responses, so asserting " +
			"control_response_within_wait==false beside captured bytes proves nothing: the " +
			"derived-from-the-count mutant reads back false here too and this test goes 0-red")
	}

	path := writeInitControlFixture(t, t.TempDir(), rec)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("#1722: read back the fixture for claude_version %q arm %q: %v",
			rec.ClaudeVersion, rec.Arm, err)
	}
	var back initControlFixtureRecord
	if err := json.Unmarshal(data, &back); err != nil {
		t.Fatalf("#1722: decode the fixture for claude_version %q arm %q: %v",
			rec.ClaudeVersion, rec.Arm, err)
	}

	// Both halves are needed and neither catches the other's mutant: the first is
	// the claim, the second is what makes the first mean something other than "the
	// field is always false".
	if back.ControlResponseWithinWait {
		t.Errorf("#1722: control_response_within_wait reads back true from a record written "+
			"with it false and %d control_responses captured; that is a field derived from "+
			"the response count instead of from the bounded wait's own result, and the main "+
			"round trip — which carries the coherent pair — stays green over it",
			len(back.ControlResponses))
	}
	if len(back.ControlResponses) == 0 {
		t.Errorf("#1722: control_responses reads back with %d entries, want the %d written; "+
			"without captured bytes on the other side, control_response_within_wait==false "+
			"above is satisfied by a field that is simply always false",
			len(back.ControlResponses), len(rec.ControlResponses))
	}
}

// --- the census -----------------------------------------------------------------

// TestInitControlFixture_DistinguishesAnEmptyCensusFromAnAbsentOne is #1731's
// second criterion: a record that RAN the redaction and needed none writes
// DIFFERENT bytes than one that never ran it, so a reader of a committed fixture
// cannot take "nothing needed redacting" for "the redactor was skipped".
//
// The whole distinction is `[]` versus `null`. dropcapRedactor.substitutions
// returns a NON-NIL EMPTY slice when nothing fired while an unfilled field is
// nil, and this record carries no `omitempty` on any tag, so the two marshal
// differently. It is one tag and one nil-normalising helper away from gone, and
// nothing else in this package notices either: writeInitControlFixture's
// `out := *rec` is a shallow copy that preserves nil-ness today, so the
// distinction reaches the file intact while every other row here stays green.
//
// THROUGH THE WRITER RATHER THAN A BARE json.Marshal, deliberately. The two
// mutants are an `omitempty` on the tag and a helper that normalises nil to empty
// ON THE WAY TO THE FILE; marshalling here directly catches only the first, and
// the writer's own marshal is what produces the bytes a reviewer of a committed
// artifact actually reads. It lands in this file rather than the record's or the
// redaction file's for the reason #1722's row does: it writes and reads back, and
// this is the file whose finOfflineExecBans entry permits os.WriteFile and
// os.ReadFile. The TestInitControlFixture_ prefix is load-bearing — this file's
// header documents a -run filter that keys on it.
//
// Deliberately NO bytes.Contains assertion pinning `"redaction": []` against
// `"redaction": null`. Inequality already reddens for every mutant in the class —
// an `omitempty` drops the key from BOTH sides, a nil-normaliser renders `[]` on
// both, a `json:"-"` drops it from both — and a literal-spelling assertion would
// additionally pin json.MarshalIndent's whitespace, which is not this row's
// subject.
//
// WHAT IT DOES NOT MEASURE, so that nobody credits it with more than it proves:
// it catches a writer-side helper that turns a NIL census non-nil. It does NOT
// catch a writer that overwrites a non-nil census with a DIFFERENT value, and
// nothing in #1731 does — that half rests on writeInitControlFixture's
// copy-and-don't-mutate contract, with #1729's byte-identity criterion as its
// future instrument.
func TestInitControlFixture_DistinguishesAnEmptyCensusFromAnAbsentOne(t *testing.T) {
	t.Parallel()

	// The same construction TestInitControlRedactRecord_LeavesAPathFreeRecordByteIdentical
	// uses — the same constructor over the same four synthetic values — so the two
	// rows stay in step rather than drifting into two different redactors. Neither
	// value is read off the environment, which is what keeps this file's ban on
	// realHome and os.TempDir untouched.
	rec := initControlFullRecord()
	red := newInitControlRedactor(
		initControlOperatorHomeValue,
		initControlTempHomeValue,
		initControlWorkdirValue,
		initControlTempDirValue,
	)
	census := redactInitControlRecord(red, rec)

	// The vacuity controls, and they must Fatalf rather than skip — precheck's
	// precedent in the cap test below. Two distinct failures, so two messages: a
	// property that cannot discriminate is a broken instrument, not a passing test.
	if census == nil {
		t.Fatalf("#1731: the pass returned a NIL census over a path-free record, so this row " +
			"compares nil against nil and `[]` versus `null` is no longer a distinction " +
			"anywhere: dropcapRedactor.substitutions stopped returning a NON-NIL EMPTY slice, " +
			"and that non-nil-ness is the entire mechanism the redaction field carries")
	}
	if len(census) != 0 {
		t.Fatalf("#1731: the pass fired %d class(es) over initControlFullRecord, so this row "+
			"compares a POPULATED census against nil and settles nothing about the EMPTY "+
			"case it exists for; that fixture acquired a path value, which also reddens "+
			"TestInitControlRedactRecord_LeavesAPathFreeRecordByteIdentical", len(census))
	}

	// Two shallow copies of the POST-PASS record, differing in exactly one field
	// and leaning on no other row's byte-identity claim. Only the new field is
	// assigned on either copy, so no slice field's backing array is touched and the
	// fresh pointer initControlFullRecord hands out stays unshared.
	ran := *rec
	ran.Redaction = census
	skipped := *rec
	skipped.Redaction = nil

	// A tempdir EACH, and not stylistic: both copies carry the same claude_version
	// and the same arm, so initControlArmFixtureName mints one filename for both
	// and a shared directory would have them overwrite each other.
	write := func(rec *initControlFixtureRecord) []byte {
		t.Helper()
		path := writeInitControlFixture(t, t.TempDir(), rec)
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("#1731: read back the fixture for claude_version %q arm %q: %v",
				rec.ClaudeVersion, rec.Arm, err)
		}
		return data
	}
	ranBytes := write(&ran)
	skippedBytes := write(&skipped)

	if bytes.Equal(ranBytes, skippedBytes) {
		// Printing both blobs is the same narrowly-scoped exception the round-trip
		// and byte-identity rows already take: every value in this record is a
		// synthetic literal, and the diagnostic is worth more than the bytes.
		// runInitControlChild fills this same record from a live child and must not
		// inherit the pattern.
		t.Errorf("#1731: a record whose redaction pass fired NOTHING wrote bytes identical to "+
			"one that never ran the pass, so a reader of a committed fixture cannot tell "+
			"\"nothing needed redacting\" from \"the redactor was skipped\": an `omitempty` on "+
			"the redaction tag drops the key from both sides, and a helper that normalises nil "+
			"to empty on the way to the file renders `[]` on both.\nran     %s\nskipped %s",
			ranBytes, skippedBytes)
	}
}

